#!/usr/bin/env python3
"""Build captions-data.ts (house sticker captions + top source tags) from words.json and a hand-written chunk spec.

usage: make_captions.py words.json captions_spec.txt out/captions-data.ts [--fps 30] [-v]

Spec format, one script line per text line, in narration order:
    TAG: <text shown in the top tag while this line plays>   (optional, applies to the NEXT line; "TAG: -" = none)
    IN *1919|A WAVE OF|*MOLASSES|...
- "|" separates caption chunks (1-3 words each, shown one chunk at a time).
- "*WORD" marks a key word: it goes in the yellow box. Adjacent key words share one box.
- Display text may differ from the spoken words (numbers as digits: "*25 *FEET"). When the number of display
  tokens differs from the spoken words it covers, append "#n" with the spoken word count: "AT *35 *MPH#5"
  covers "at thirty-five miles an hour".
- Words you drop from the display (e.g. "and") must still be counted with #n.
The script asserts that the chunks cover words.json exactly and prints the mapping with -v so you can check it.
"""
import json, sys

args = [a for a in sys.argv[1:] if not a.startswith("-")]
FPS = int(sys.argv[sys.argv.index("--fps") + 1]) if "--fps" in sys.argv else 30
if "--fps" in sys.argv: args.remove(str(FPS))
words_path, spec_path, out_path = args[:3]
W = json.load(open(words_path))

lines, pending_tag = [], None
for raw in open(spec_path, encoding="utf-8"):
    raw = raw.strip()
    if not raw or raw.startswith("//"): continue
    if raw.startswith("TAG:"):
        t = raw[4:].strip(); pending_tag = None if t == "-" else t; continue
    lines.append((raw, pending_tag)); pending_tag = None

i, chunks, tagged = 0, [], []
for spec, tag in lines:
    first = i
    for c in spec.split("|"):
        c = c.strip(); n = None
        if "#" in c: c, n = c.rsplit("#", 1); n = int(n)
        toks = c.split(); n = n or len(toks)
        ws = W[i:i + n]; i += n
        assert ws, f"ran out of words at chunk '{c}'"
        chunks.append(dict(toks=[[t.lstrip("*"), t.startswith("*")] for t in toks], s=ws[0]["start"], e=ws[-1]["end"],
                           w=" ".join(x["word"] for x in ws)))
    tagged.append(dict(s=W[first]["start"], e=W[i - 1]["end"], tag=tag))
assert i == len(W), f"spec covers {i} words, words.json has {len(W)}"

out = []
for k, c in enumerate(chunks):
    last = k + 1 == len(chunks)
    nxt = c["e"] + 0.6 if last else chunks[k + 1]["s"]
    a = max(0, round(c["s"] * FPS) - 1)
    if last: b = round((c["e"] + 0.6) * FPS)
    elif nxt - c["e"] < 0.45: b = round(nxt * FPS) - 2
    else: b = round(min(nxt, c["e"] + 0.45) * FPS) - 1
    out.append(dict(a=a, b=b, t=c["toks"]))
    if "-v" in sys.argv:
        print(a, b, c["w"], "=>", " ".join(f"[{t}]" if key else t for t, key in c["toks"]))

tags = []  # one tag per line; identical consecutive tags merge so they do not re-animate
for l in tagged:
    if not l["tag"]: continue
    a, b = round(l["s"] * FPS), round(l["e"] * FPS) + 6
    if tags and tags[-1]["text"] == l["tag"] and a - tags[-1]["b"] < 10: tags[-1]["b"] = b
    else: tags.append(dict(a=a, b=b, text=l["tag"]))

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// Generated by make_captions.py from words.json (voice starts at frame 0).\n")
    f.write("export const CHUNKS: { a: number; b: number; t: [string, boolean][] }[] = " + json.dumps(out, ensure_ascii=False) + ";\n")
    f.write("export const TAGS: { a: number; b: number; text: string }[] = " + json.dumps(tags, ensure_ascii=False) + ";\n")
print(len(out), "chunks,", len(tags), "tags ->", out_path)
